CREATE TABLE app_user (
                          id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                          version BIGINT NOT NULL DEFAULT 0,

                          username VARCHAR(64) NOT NULL,
                          display_name VARCHAR(150) NOT NULL,
                          password_hash VARCHAR(255) NOT NULL,
                          role VARCHAR(20) NOT NULL,

                          enabled BOOLEAN NOT NULL DEFAULT TRUE,
                          password_change_required BOOLEAN NOT NULL DEFAULT TRUE,
                          security_version BIGINT NOT NULL DEFAULT 0,

                          created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
                          updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,

                          CONSTRAINT uk_app_user_username
                              UNIQUE (username),

                          CONSTRAINT chk_app_user_username
                              CHECK (username ~ '^[a-z0-9][a-z0-9._-]{2,63}$'),

    CONSTRAINT chk_app_user_display_name
        CHECK (btrim(display_name) <> ''),

    CONSTRAINT chk_app_user_password_hash
        CHECK (btrim(password_hash) <> ''),

    CONSTRAINT chk_app_user_role
        CHECK (role IN ('READ_ONLY', 'EDITOR', 'ADMIN')),

    CONSTRAINT chk_app_user_versions
        CHECK (version >= 0 AND security_version >= 0)
);