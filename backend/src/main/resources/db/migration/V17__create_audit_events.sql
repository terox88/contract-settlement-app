CREATE TABLE audit_event (
                             id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                             occurred_at TIMESTAMPTZ NOT NULL,
                             system_actor BOOLEAN NOT NULL DEFAULT FALSE,
                             actor_id BIGINT,
                             actor_username VARCHAR(64),
                             actor_display_name VARCHAR(150) NOT NULL,
                             operation VARCHAR(64) NOT NULL,
                             entity_type VARCHAR(64) NOT NULL,
                             entity_id BIGINT NOT NULL,
                             entity_label VARCHAR(500) NOT NULL,
                             task_id BIGINT,
                             main_contract_id BIGINT,
                             subcontract_id BIGINT,
                             changes JSONB NOT NULL,
                             reason VARCHAR(2000),

                             CONSTRAINT chk_audit_event_actor CHECK (
                                 (system_actor AND actor_id IS NULL AND actor_username IS NULL)
                                     OR
                                 (NOT system_actor AND actor_id IS NOT NULL
                                     AND actor_username IS NOT NULL
                                     AND btrim(actor_username) <> '')
                                 ),

                             CONSTRAINT chk_audit_event_actor_name
                                 CHECK (btrim(actor_display_name) <> ''),

                             CONSTRAINT chk_audit_event_operation
                                 CHECK (btrim(operation) <> ''),

                             CONSTRAINT chk_audit_event_entity_type
                                 CHECK (btrim(entity_type) <> ''),

                             CONSTRAINT chk_audit_event_entity_label
                                 CHECK (btrim(entity_label) <> ''),

                             CONSTRAINT chk_audit_event_changes
                                 CHECK (jsonb_typeof(changes) = 'array')
);

CREATE INDEX idx_audit_event_time
    ON audit_event (occurred_at DESC, id DESC);

CREATE INDEX idx_audit_event_entity
    ON audit_event (
                    entity_type,
                    entity_id,
                    occurred_at DESC,
                    id DESC
        );

CREATE INDEX idx_audit_event_task
    ON audit_event (task_id, occurred_at DESC, id DESC)
    WHERE task_id IS NOT NULL;